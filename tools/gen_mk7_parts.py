#!/usr/bin/env python3
"""Generate Mk7-spec derived parts from the user's OWN BeamNG install.

Reads base-game parts from vivace.zip, copies them under NEW part names with Mk7 values, and writes
vehicles/vivace/generated/mk7_parts.generated.jbeam. That output contains base-game data, is gitignored
(see .gitignore) and must never be committed or shipped. Re-run after a game update.

Usage:  python -I tools/gen_mk7_parts.py [path/to/vivace.zip]
Values and sources: docs/MK7_SPEC_TARGETS.md (brake disc sizes: VW newsroom; fuel: 50 L GTI / 55 L R).
Brake torque / disc mass scaling is a FIRST ESTIMATE (see docs/BASE_VALUES.md) and needs in-game calibration.
"""
import os, re, sys, zipfile

DEFAULT_ZIP = r'D:\SteamLibrary\steamapps\common\BeamNG.drive\content\vehicles\vivace.zip'
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'vehicles', 'vivace', 'generated', 'mk7_parts.generated.jbeam')

# front vented: torque ~ 9000 * diameter(m); rear: ~ 4500 * diameter(m) (extrapolated from the base sport parts)
BRAKES = {
    # new name: (base part, display name, torque, diameter m, brakeMass kg, brakeType or None)
    'vivace_brake_F_mk7_gti': ('vivace_brake_F_sport',   'Mk7 GTI Front Disc Brakes 314x30', 2826, 0.314, 9.25, None),
    'vivace_brake_R_mk7_gti': ('vivace_brake_R_sport',   'Mk7 GTI Rear Disc Brakes 300x12',  1350, 0.300, 5.5,  None),
    'vivace_brake_F_mk7_pp':  ('vivace_brake_F_sport_r', 'Mk7 GTI PP / R Front Disc Brakes 340x30', 3060, 0.340, 9.9, None),
    'vivace_brake_R_mk7_pp':  ('vivace_brake_R_sport_r', 'Mk7 GTI PP / R Rear Disc Brakes 310x22',  1395, 0.310, 6.6, None),
}
FUEL = {'vivace_fueltank_mk7_55': ('vivace_fueltank', 'Gasoline Fuel Tank 55 L (Mk7 R)', 55)}


def extract(text, name):
    lines = text.replace('\r\n', '\n').split('\n')
    start = None
    for i, l in enumerate(lines):
        if re.match(r'^"%s"\s*:\s*\{?\s*$' % re.escape(name), l.rstrip()):
            start = i
            break
    if start is None:
        raise SystemExit('base part not found: ' + name)
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if re.match(r'^"[A-Za-z0-9_.]+"\s*:', lines[j]):
            end = j
            break
    body = '\n'.join(lines[start:end]).rstrip()
    # strip the trailing top-level comma/closing of the whole file if we grabbed it
    body = re.sub(r'\n\}\s*$', '', body) if body.rstrip().endswith('}\n}') else body
    return body


def sub_once(pattern, repl, s, what):
    new, n = re.subn(pattern, repl, s, count=1)
    if n != 1:
        raise SystemExit('pattern not found (%s): %s' % (what, pattern))
    return new


def make_brake(new, spec, src):
    base, title, torque, dia, mass, _ = spec
    b = extract(src, base)
    b = sub_once(r'^"%s"' % re.escape(base), '"%s"' % new, b, 'header')
    b = sub_once(r'("name"\s*:\s*)"[^"]*"', r'\1"%s"' % title, b, 'name')
    b = sub_once(r'"brakeTorque"\s*:\s*"\$=\$brakestrength\*[0-9.]+"', '"brakeTorque":"$=$brakestrength*%d"' % torque, b, 'torque')
    b = sub_once(r'"brakeDiameter"\s*:\s*[0-9.]+', '"brakeDiameter":%.3f' % dia, b, 'diameter')
    b = sub_once(r'"brakeMass"\s*:\s*[0-9.]+', '"brakeMass":%s' % mass, b, 'mass')
    return b.rstrip().rstrip(',') + ','


def make_fuel(new, spec, src):
    base, title, litres = spec
    b = extract(src, base)
    b = sub_once(r'^"%s"' % re.escape(base), '"%s"' % new, b, 'header')
    b = sub_once(r'("name"\s*:\s*)"[^"]*"', r'\1"%s"' % title, b, 'name')
    b = sub_once(r'"fuelCapacity"\s*:\s*[0-9.]+', '"fuelCapacity": %d' % litres, b, 'capacity')
    b = sub_once(r'("\$fuel"\s*,\s*"range"\s*,\s*"L"\s*,\s*"Chassis"\s*,\s*)[0-9.]+(\s*,\s*0\s*,\s*)[0-9.]+',
                 r'\g<1>%d\g<2>%d' % (litres, litres), b, 'fuel variable')
    return b.rstrip().rstrip(',') + ','


def main():
    zpath = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_ZIP
    z = zipfile.ZipFile(zpath)
    brakes_src = z.read('vehicles/vivace/vivace_brakes.jbeam').decode('utf8', 'replace')
    fuel_src = z.read('vehicles/vivace/vivace_fueltank.jbeam').decode('utf8', 'replace')
    parts = [make_brake(n, s, brakes_src) for n, s in BRAKES.items()]
    parts += [make_fuel(n, s, fuel_src) for n, s in FUEL.items()]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf8', newline='\n') as f:
        f.write('// GENERATED by tools/gen_mk7_parts.py from the local BeamNG install. Contains base-game data: do NOT commit or distribute.\n{\n')
        f.write('\n'.join(parts))
        f.write('\n}\n')
    print('wrote', os.path.normpath(OUT), '-', len(parts), 'parts')


if __name__ == '__main__':
    main()
